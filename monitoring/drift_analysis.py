"""Production data analysis: data drift + operational anomalies.

The API logs every /predict to MLflow (full input as an input.json artifact,
processing_time_ms as a metric). This script builds the production dataset
from those runs (local MLflow store) or from an exported JSONL of payloads,
compares it with the training reference (data/raw/application_train.csv
restricted to the 22 model columns) and runs Evidently's statistical tests
(K-S per numeric column, Z-test per categorical, threshold 0.05).

Outputs (monitoring/output/ by default):
- drift_summary[_label].json: machine-readable summary consumed by the
  dashboard's Drift tab
- drift_report[_label].html: Evidently per-feature report

Local PoC as allowed by the project brief: data generated by the cloud API
can be exported (see monitoring/generate_traffic.py --save-payloads) and
analyzed locally.

Usage:
    uv run python monitoring/drift_analysis.py                    # MLflow source
    uv run python monitoring/drift_analysis.py --label shifted \
        --inputs-file monitoring/output/payloads_shifted.jsonl
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

import pandas as pd

# Allow running both as a module and as a script from the repo root
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from api.ml_pipeline import TOP_FORM_FIELDS  # noqa: E402

DEFAULT_TRACKING_URI = os.getenv("MLFLOW_TRACKING_URI", "sqlite:///tracking/mlflow.db")
DEFAULT_EXPERIMENT = os.getenv("MLFLOW_EXPERIMENT", "credit_scoring_api")
DEFAULT_REFERENCE = os.path.join("data", "raw", "application_train.csv")
DEFAULT_SCHEMA = os.path.join("api", "schema", "raw_columns.json")
DEFAULT_OUT_DIR = os.path.join("monitoring", "output")
DEFAULT_REQUESTS_LOG = os.getenv("REQUESTS_LOG_FILE",
                                os.path.join("tracking", "api_requests.jsonl"))

# p95 inference time above this is flagged as an operational anomaly
# (the deployed API averages ~10-70 ms; 500 ms would signal a real problem)
LATENCY_P95_ALERT_MS = 500.0
# Error rate (4xx + 5xx share of served requests) above this is flagged as
# an operational anomaly. 4xx are included: a spike of validation errors
# usually means a broken client integration, worth investigating as well.
ERROR_RATE_ALERT = 0.05
# Below this many production samples the statistical tests are meaningless
MIN_PRODUCTION_SAMPLES = 20
# Drift threshold per column: p-value under this = drifted. Corrected
# for the 22 simultaneous comparisons (Bonferroni-lite: 0.05/22 = 0.002
# would be the strict bound; 0.01 keeps sensitivity while suppressing the
# small-sample false positives observed with the naive 0.05 cut).
DRIFT_THRESHOLD = 0.01
# Features carrying most of the model's gain (~99% via EXT_SOURCE_1-3):
# a drift on any of these deserves an alert even if the dataset-level
# share of drifted columns stays below Evidently's 50% default.
CRITICAL_FEATURES = ["EXT_SOURCE_1", "EXT_SOURCE_2", "EXT_SOURCE_3", "DAYS_BIRTH"]

# Evidently statistics whose value is a distribution distance (drifted when
# the value EXCEEDS the threshold), as opposed to p-value statistics
# (K-S, Z-test: drifted when the value is BELOW the threshold).
DISTANCE_METHODS = {"wasserstein", "psi", "tvd", "kl_div", "jensenshannon",
                    "hellinger", "ed", "es", "empirical_mmd"}


def _parse_since(value: str) -> int:
    """ISO datetime or relative hours ('-6h') -> epoch milliseconds."""
    from datetime import timedelta
    v = value.strip()
    if v.endswith("h") and (v[:-1].lstrip("-").isdigit()):
        dt = datetime.now(timezone.utc) - timedelta(hours=abs(int(v[:-1])))
    else:
        dt = datetime.fromisoformat(v)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
    return int(dt.timestamp() * 1000)


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------

def load_schema_fields(schema_path: str) -> List[Dict[str, Any]]:
    """Load the raw field definitions (name, type, default=median/mode)."""
    with open(schema_path, encoding="utf-8") as f:
        return json.load(f)["fields"]


def align_to_schema(df: pd.DataFrame, fields: List[Dict[str, Any]]) -> pd.DataFrame:
    """Restrict to the schema columns, cast types and impute nulls.

    Production payloads may omit fields (the API imputes them server-side
    with the training median/mode stored in the schema); the analysis does
    the same so the comparison reflects what the model actually saw.
    """
    import numpy as np

    n = len(df)
    cols: Dict[str, pd.Series] = {}
    for f in fields:
        name = f["name"]
        if f["type"] == "categorical":
            if name in df:
                series = df[name].astype(object)
            else:
                series = pd.Series([None] * n, dtype=object)
            cols[name] = series.fillna(f["default"]).astype(str).reset_index(drop=True)
        else:
            if name in df:
                series = pd.to_numeric(df[name], errors="coerce")
            else:
                series = pd.Series([np.nan] * n, dtype=float)
            cols[name] = series.fillna(float(f["default"])).reset_index(drop=True)
    return pd.DataFrame(cols)


def load_reference(
    reference_csv: str,
    fields: List[Dict[str, Any]],
    max_rows: int = 20000,
) -> pd.DataFrame:
    """Training reference: application_train restricted to the model columns."""
    names = [f["name"] for f in fields]
    df = pd.read_csv(reference_csv, usecols=names)
    df = df.sample(n=min(len(df), max_rows), random_state=42)
    return align_to_schema(df, fields)


def load_production_from_mlflow(
    tracking_uri: str,
    experiment: str,
    fields: List[Dict[str, Any]],
    since: Optional[str] = None,
    until: Optional[str] = None,
) -> tuple:
    """Production inputs + latency metrics from the API's MLflow runs.

    Returns (dataframe, latencies_ms, n_runs, first_ts, last_ts).
    """
    import mlflow
    from mlflow.tracking import MlflowClient

    mlflow.set_tracking_uri(tracking_uri)
    client = MlflowClient()
    exp = client.get_experiment_by_name(experiment)
    if exp is None:
        raise SystemExit(f"Experiment '{experiment}' not found in {tracking_uri}")

    runs = client.search_runs([exp.experiment_id],
                              filter_string="tags.source = 'api'",
                              order_by=["attributes.start_time ASC"])
    since_ms = _parse_since(since) if since else None
    until_ms = _parse_since(until) if until else None
    if since_ms is not None or until_ms is not None:
        filtered = [r for r in runs
                    if (since_ms is None or r.info.start_time >= since_ms)
                    and (until_ms is None or r.info.start_time <= until_ms)]
        runs = filtered  # type: ignore[assignment]

    payloads: List[Dict[str, Any]] = []
    latencies: List[float] = []
    first_ts: Optional[str] = None
    last_ts: Optional[str] = None
    for run in runs:
        try:
            local_path = client.download_artifacts(run.info.run_id, "input.json")
            with open(local_path, encoding="utf-8") as f:
                payloads.append(json.load(f))
        except Exception:
            continue  # run without input artifact: skip
        if "processing_time_ms" in run.data.metrics:
            latencies.append(float(run.data.metrics["processing_time_ms"]))
        ts = datetime.fromtimestamp(run.info.start_time / 1000, tz=timezone.utc)
        ts_iso = ts.isoformat()
        first_ts = ts_iso if first_ts is None else first_ts
        last_ts = ts_iso

    df = pd.DataFrame(payloads)
    if df.empty:
        return df, latencies, len(runs), first_ts, last_ts
    return align_to_schema(df, fields), latencies, len(runs), first_ts, last_ts


def load_production_from_file(
    path: str,
    fields: List[Dict[str, Any]],
) -> pd.DataFrame:
    """Production payloads exported as JSONL or a JSON list of objects."""
    with open(path, encoding="utf-8") as f:
        content = f.read().strip()
    if content.startswith("["):
        payloads = json.loads(content)
    else:
        payloads = [json.loads(line) for line in content.splitlines() if line.strip()]
    return align_to_schema(pd.DataFrame(payloads), fields)


# ---------------------------------------------------------------------------
# Drift analysis (Evidently)
# ---------------------------------------------------------------------------

def run_drift(
    reference_df: pd.DataFrame,
    current_df: pd.DataFrame,
    fields: List[Dict[str, Any]],
) -> tuple:
    """Run Evidently's DataDriftPreset and extract a machine-readable summary.

    Returns (summary_dict, snapshot): the snapshot is returned so the caller
    can also save the per-feature HTML report without re-running the tests.

    Per-column drift: p-value of the statistical test (K-S for numeric,
    Z-test for categorical); drifted when p < DRIFT_THRESHOLD. Dataset
    drift: when at least half of the columns drifted (Evidently default).
    """
    from evidently import Report
    from evidently.presets import DataDriftPreset

    # Explicit statistical tests (K-S numeric, Z-test categorical) instead
    # of Evidently's auto-selection (Wasserstein), so the threshold has a
    # clean p-value interpretation across all 22 columns.
    report = Report([DataDriftPreset(
        num_method="ks", num_threshold=DRIFT_THRESHOLD,
        cat_method="z", cat_threshold=DRIFT_THRESHOLD,
    )])
    snapshot = report.run(reference_data=reference_df, current_data=current_df)
    metrics = json.loads(snapshot.json())["metrics"]

    numeric = {f["name"] for f in fields if f["type"] != "categorical"}
    per_feature: List[Dict[str, Any]] = []
    for m in metrics:
        if not m.get("metric_name", "").startswith("ValueDrift"):
            continue
        column = m["config"]["column"]
        method = str(m["config"].get("method", ""))
        threshold = float(m["config"].get("threshold", DRIFT_THRESHOLD))
        value = float(m["value"])
        # Evidently supports two kinds of statistic: p-values (K-S, Z-test,
        # drifted when BELOW the threshold) and distribution distances
        # (Wasserstein, PSI..., drifted when ABOVE the threshold).
        if method in DISTANCE_METHODS:
            drift_detected = bool(value > threshold)
        else:
            drift_detected = bool(value < threshold)
        per_feature.append({
            "feature": column,
            "feature_type": "numeric" if column in numeric else "categorical",
            "test": method,
            "value": value,
            "threshold": threshold,
            "drift_detected": drift_detected,
        })

    drifted = sum(1 for f in per_feature if f["drift_detected"])
    n_columns = len(per_feature)
    summary = {
        "per_feature": sorted(per_feature, key=lambda f: (not f["drift_detected"], f["value"])),
        "n_columns": n_columns,
        "n_drifted_columns": drifted,
        "share_drifted_columns": round(drifted / n_columns, 4) if n_columns else 0.0,
        "dataset_drift": bool(n_columns and drifted / n_columns >= 0.5),
    }
    return summary, snapshot


# ---------------------------------------------------------------------------
# Operational analysis (latency)
# ---------------------------------------------------------------------------

def analyze_latency(latencies_ms: List[float],
                    p95_alert_ms: float = LATENCY_P95_ALERT_MS) -> Dict[str, Any]:
    """Latency stats + anomaly flag from the production metrics."""
    if not latencies_ms:
        return {"n_samples": 0, "p95_anomaly": None}
    s = sorted(latencies_ms)
    n = len(s)
    k = (n - 1) * 0.95
    f_idx = int(k)
    c_idx = min(f_idx + 1, n - 1)
    p95 = s[f_idx] + (s[c_idx] - s[f_idx]) * (k - f_idx)
    return {
        "n_samples": n,
        "avg_ms": round(sum(s) / n, 2),
        "p95_ms": round(p95, 2),
        "max_ms": round(s[-1], 2),
        "p95_alert_ms": p95_alert_ms,
        "p95_anomaly": bool(p95 > p95_alert_ms),
    }


# ---------------------------------------------------------------------------
# Operational analysis (error rate, from the API's request log)
# ---------------------------------------------------------------------------

def load_requests_log(path: str) -> List[Dict[str, Any]]:
    """Request events written by the API middleware (one JSON object per line)."""
    events: List[Dict[str, Any]] = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                events.append(json.loads(line))
    return events


def analyze_errors(events: List[Dict[str, Any]],
                   alert_rate: float = ERROR_RATE_ALERT) -> Dict[str, Any]:
    """Error-rate stats + anomaly flag from the request log.

    A missing status_code means an unhandled exception (5xx, as counted by
    the API middleware).
    """
    if not events:
        return {"n_requests": 0, "error_rate": None, "error_rate_anomaly": None}
    n = len(events)
    n_4xx = sum(1 for e in events
                if e.get("status_code") is not None and 400 <= e["status_code"] < 500)
    n_5xx = sum(1 for e in events
                if e.get("status_code") is None or e["status_code"] >= 500)
    n_errors = n_4xx + n_5xx
    rate = n_errors / n
    return {
        "n_requests": n,
        "n_errors": n_errors,
        "errors_4xx": n_4xx,
        "errors_5xx": n_5xx,
        "error_rate": round(rate, 4),
        "error_rate_alert": alert_rate,
        "error_rate_anomaly": bool(rate > alert_rate),
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--inputs-file", default=None,
                        help="JSONL/JSON file of production payloads (alternative to MLflow)")
    parser.add_argument("--label", default="baseline",
                        help="Label written into the output filenames and summary")
    parser.add_argument("--tracking-uri", default=DEFAULT_TRACKING_URI)
    parser.add_argument("--experiment", default=DEFAULT_EXPERIMENT)
    parser.add_argument("--reference", default=DEFAULT_REFERENCE)
    parser.add_argument("--schema", default=DEFAULT_SCHEMA)
    parser.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    parser.add_argument("--max-reference-rows", type=int, default=20000)
    parser.add_argument("--min-samples", type=int, default=MIN_PRODUCTION_SAMPLES)
    parser.add_argument("--since", default=None,
                        help="Only analyze API runs created after this time "
                             "(ISO datetime or '-N h' like '-6h'). Filters out "
                             "older test-pollution runs in the local store.")
    parser.add_argument("--until", default=None,
                        help="Only analyze API runs created before this time "
                             "(ISO datetime or '-N h').")
    parser.add_argument("--requests-file", default=DEFAULT_REQUESTS_LOG,
                        help="JSONL request log written by the API middleware: "
                             "error-rate analysis (and request latency when "
                             "MLflow provides none). Skipped if missing; pass "
                             "'' to disable.")
    args = parser.parse_args()

    fields = load_schema_fields(args.schema)
    print(f"Reference: {args.reference} (up to {args.max_reference_rows} rows)")
    reference_df = load_reference(args.reference, fields, args.max_reference_rows)

    latencies: List[float] = []
    source_info: Dict[str, Any] = {}
    if args.inputs_file:
        print(f"Production data: {args.inputs_file}")
        current_df = load_production_from_file(args.inputs_file, fields)
        source_info = {"type": "inputs_file", "path": args.inputs_file}
    else:
        print(f"Production data: MLflow experiment '{args.experiment}' ({args.tracking_uri})")
        current_df, latencies, n_runs, first_ts, last_ts = load_production_from_mlflow(
            args.tracking_uri, args.experiment, fields,
            since=args.since, until=args.until)
        source_info = {"type": "mlflow", "experiment": args.experiment,
                       "tracking_uri": args.tracking_uri, "n_runs": n_runs,
                       "first_prediction": first_ts, "last_prediction": last_ts}

    n_prod = len(current_df)
    print(f"Production samples: {n_prod} | reference rows: {len(reference_df)}")

    # Operational analysis of the request log: error rate (always) and
    # request latency (only when the MLflow source gave none, e.g. the
    # inputs-file mode has no per-prediction metrics).
    errors_summary: Optional[Dict[str, Any]] = None
    if args.requests_file and os.path.exists(args.requests_file):
        events = load_requests_log(args.requests_file)
        errors_summary = analyze_errors(events)
        source_info["requests_log"] = {"path": args.requests_file,
                                       "n_requests": len(events)}
        if not latencies:
            latencies = [float(e["duration_ms"]) for e in events
                         if e.get("path") == "/predict"
                         and e.get("status_code") == 200
                         and "duration_ms" in e]
    elif args.requests_file:
        print(f"Requests log not found ({args.requests_file}): "
              "error-rate analysis skipped.")
    latency_summary = analyze_latency(latencies)

    if n_prod < args.min_samples:
        print(f"WARNING: fewer than {args.min_samples} samples: statistical "
              "tests would be meaningless. Writing an 'insufficient_samples' summary.")
        drift = {"per_feature": [], "n_columns": 0, "n_drifted_columns": 0,
                 "share_drifted_columns": 0.0, "dataset_drift": None}
        critical_drifted: List[str] = []
        status = "insufficient_samples"
        snapshot = None
    else:
        drift, snapshot = run_drift(reference_df, current_df, fields)
        critical_drifted = [f["feature"] for f in drift["per_feature"]
                            if f["drift_detected"] and f["feature"] in CRITICAL_FEATURES]
        if drift["dataset_drift"]:
            status = "drift_detected"
        elif critical_drifted:
            status = "alert_critical_features"
        else:
            status = "stable"

    operational_anomaly = bool(
        latency_summary.get("p95_anomaly")
        or (errors_summary or {}).get("error_rate_anomaly")
    )
    summary = {
        "label": args.label,
        "status": status,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "n_production_samples": n_prod,
        "n_reference_rows": int(len(reference_df)),
        "reference": {"dataset": "application_train",
                      "columns": "the 22 raw model columns"},
        "source": source_info,
        "drift": drift,
        "critical_features": CRITICAL_FEATURES,
        "critical_features_drifted": critical_drifted,
        "latency": latency_summary,
        "errors": errors_summary,
        "operational_anomaly": operational_anomaly,
        "thresholds": {"p_value": DRIFT_THRESHOLD,
                       "latency_p95_alert_ms": LATENCY_P95_ALERT_MS,
                       "error_rate_alert": ERROR_RATE_ALERT,
                       "dataset_drift_share": 0.5},
    }

    os.makedirs(args.out_dir, exist_ok=True)
    suffix = "" if args.label == "baseline" else f"_{args.label}"
    summary_path = os.path.join(args.out_dir, f"drift_summary{suffix}.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    print(f"Summary written: {summary_path}")

    if snapshot is not None:
        html_path = os.path.join(args.out_dir, f"drift_report{suffix}.html")
        snapshot.save_html(html_path)
        print(f"HTML report: {html_path}")

    per_feature: List[Dict[str, Any]] = drift.get("per_feature", [])  # type: ignore[assignment]
    drifted_features = [f["feature"] for f in per_feature if f["drift_detected"]]
    print(f"Status: {status} | drifted columns: "
          f"{drift['n_drifted_columns']}/{drift['n_columns']}"
          + (f" ({', '.join(drifted_features)})" if drifted_features else ""))
    if errors_summary:
        print(f"Error rate: {errors_summary['error_rate'] * 100:.1f}% "
              f"of {errors_summary['n_requests']} requests "
              f"({errors_summary['n_errors']} errors) | anomaly: "
              f"{errors_summary['error_rate_anomaly']}")
    if operational_anomaly:
        print("Operational anomaly detected (latency p95 and/or error rate "
              "above the alert threshold).")


if __name__ == "__main__":
    main()
